#!/usr/bin/env node
// Writes the retired release-directory MCP launch paths into a staged
// one-component release, so an MCP client configuration that still names the
// pre-consolidation layout keeps reaching the same server. COMPATIBILITY.md
// rows "MCP launch path".
//
//   node scripts/stage-legacy-launch-paths.mjs <release-dir>
//
// Why a staging script and not committed files: `dist/` is ignored in this
// repository, so a forwarder committed at the root would never reach a release
// directory — and `<release>/helmo-roadmap/` is a SIBLING of the checkout, a
// path no file inside the checkout can occupy. Both retired paths are
// properties of the staged directory, so the directory is what this writes to.
//
// The forwarder imports the real server by a relative path, so the release
// directory stays movable, and the import leaves the running module's own
// location alone — which is what the release pin reads. A forwarded start is
// pinned exactly as a direct one is.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

/** The date these two paths stop working on, as published in COMPATIBILITY.md. */
export const RETIRES = '2027-04-01';

/**
 * The retired path, and the entry inside the one-component layout it stands
 * in for. `from` is relative to the release directory; `to` is relative to
 * the retired path's own directory.
 */
export const FORWARDS = [
  {
    from: join('helmo', 'dist', 'server.js'),
    to: join('..', 'packages', 'work', 'dist', 'server.js'),
    old: '<release>/helmo/dist/server.js',
    now: 'helmo mcp work',
  },
  {
    from: join('helmo-roadmap', 'dist', 'server.js'),
    to: join('..', '..', 'helmo', 'packages', 'roadmap', 'dist', 'server.js'),
    old: '<release>/helmo-roadmap/dist/server.js',
    now: 'helmo mcp roadmap',
  },
];

/** Marks a file as ours, so a re-run can tell its own output from a real build. */
export const BANNER = 'Retired Helmo release-directory launch path.';

export function forwarderSource({ to, old, now }) {
  // Everything this prints goes to stderr: stdout is the MCP protocol channel.
  return `#!/usr/bin/env node
// ${BANNER} Generated by scripts/stage-legacy-launch-paths.mjs.
if (Date.now() > Date.parse('${RETIRES}T23:59:59.999Z')) {
  console.error("${old} stopped working after ${RETIRES}; name this release's own packages/ entry, or run '${now}'.");
  process.exit(2);
}
console.error(
  "${old} is a retired layout — this path forwards for two more releases and refuses after ${RETIRES} (COMPATIBILITY.md).",
);
await import('${to.split(/[\\/]/).join('/')}');
`;
}

/**
 * A legacy release directory holds the real `helmo/dist/server.js` and
 * `helmo-roadmap/dist/server.js` builds. Writing a forwarder over either one
 * would destroy the release it was asked to make compatible, so the layout is
 * checked before anything is written — not per file, where the first write
 * would already have landed.
 */
export function assertStageable(releaseDir) {
  const manifestPath = join(releaseDir, 'RELEASE.json');
  if (!existsSync(manifestPath)) throw new Error(`no RELEASE.json in ${releaseDir} — not a release directory`);
  const commits = JSON.parse(readFileSync(manifestPath, 'utf8')).commits ?? {};
  const names = Object.keys(commits);
  if (names.length !== 1 || names[0] !== 'helmo') {
    throw new Error(
      `refusing to stage into a ${names.sort().join('/') || 'nameless'} release: these paths are that layout's real builds`,
    );
  }
  for (const forward of FORWARDS) {
    const target = resolve(releaseDir, dirname(forward.from), forward.to);
    if (!existsSync(target)) throw new Error(`nothing to forward to: ${target} does not exist`);
    const path = join(releaseDir, forward.from);
    if (existsSync(path) && !readFileSync(path, 'utf8').includes(BANNER)) {
      throw new Error(`refusing to overwrite ${path}: it is not a generated forwarder`);
    }
  }
}

export function stageLegacyLaunchPaths(releaseDir) {
  assertStageable(releaseDir);
  const written = [];
  for (const forward of FORWARDS) {
    const path = join(releaseDir, forward.from);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, forwarderSource(forward));
    written.push(path);
  }
  return written;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const releaseDir = process.argv[2];
  if (!releaseDir) {
    console.error('usage: stage-legacy-launch-paths.mjs <release-dir>');
    process.exit(2);
  }
  const root = resolve(releaseDir);
  try {
    for (const path of stageLegacyLaunchPaths(root)) console.log(path);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
